def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def main():
    os.makedirs(SEEDS_DIR, exist_ok=True)
    unknown = sorted((set(EXTRA) | set(GAPS)) - set(CURATED))
    if unknown:
        raise SystemExit(f"EXTRA/GAPS entry for uncurated insurer: {', '.join(unknown)}")
    total = 0
    for name, (category, urls) in CURATED.items():
        merged = list(dict.fromkeys(urls + EXTRA.get(name, []) + GAPS.get(name, [])))
        path = os.path.join(SEEDS_DIR, f"{slug(name)}.csv")
        with open(path, "w", newline="", encoding="utf-8") as handle:
            writer = csv.writer(handle)
            writer.writerow(["insurer", "url", "product", "category"])
            for url in merged:
                product = url.rstrip("/").split("/")[-1]
                product = re.sub(r"\.html?$", "", product)
                product = re.sub(r"[-_]+", " ", product).strip().title()
                writer.writerow([name, url, product or "Insurance", category])
        total += len(merged)
        print(f"{name:<34} {len(merged):>3} seeds -> {path}")
    print(f"TOTAL {total} seed URLs across {len(CURATED)} insurers")


if __name__ == "__main__":
    main()
